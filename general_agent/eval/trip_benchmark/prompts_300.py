def _behaviors(pid: int, bucket: str, prompt: str) -> list[str]:
    """Multiple expected behaviors — not a single gold itinerary."""
    b = [
        "Answer the actual ask; don't dump a generic city brochure.",
        "Distinguish confirmed vs estimated vs unknown.",
        "Do not invent live fares, hotel rates, visa rules, or availability.",
        "If a schedule is physically impossible, say so and cut stops.",
    ]
    p = prompt.lower()
    if "₹" in prompt or "$" in prompt or "budget" in p or "lakh" in p:
        b.append("Stay inside the stated budget or declare it impossible with a cheaper alternative.")
    if any(x in p for x in ("no car", "without a car", "without renting", "metro", "walking", "amtrak")):
        b.append("Honor the transport constraint; do not sneak in a rental car.")
    if any(x in p for x in ("vegetarian", "egg", "seafood")):
        b.append("Every meal suggestion must fit the diet (pure veg = no egg).")
    if any(x in p for x in ("don't drink", "dont drink", "sober", "no alcohol")):
        b.append("No alcohol-centric venues as the main plan.")
    if any(x in p for x in ("18", "19", "21", "under-21")):
        b.append("Flag hotel check-in age and 21+ nightlife; do not assume 18 can book any US hotel.")
    if any(x in p for x in ("visa", "schengen", "passport", "transit", "immigration")):
        b.append("Search or refuse to guess immigration; cite official/unknown, never invent.")
    if any(x in p for x in ("wheelchair", "elderly", "stairs", "accessible")):
        b.append("Minimize stairs/walking; pick actually accessible sights or admit uncertainty.")
    if any(x in p for x in ("rain", "monsoon", "44", "heat", "weather")):
        b.append("Change the day plan for weather; don't keep outdoor midday sightseeing.")
    if any(x in p for x in ("cancelled", "canceled", "missed", "landslide", "waitlist", "rac", "rebuild", "replan")):
        b.append("Replan the trip, not just empathize; keep constraints.")
    if bucket in ("A",) and any(x in p for x in ("mumbai", "delhi", "bangalore", "jaipur", "kolkata")):
        b.append("Order stops by neighborhood; no Andheri→Colaba→Bandra ping-pong.")
    if pid in (41, 42, 43, 102, 175, 257):
        b.append("Cut or reorder destinations; do not pretend the original list fits.")
